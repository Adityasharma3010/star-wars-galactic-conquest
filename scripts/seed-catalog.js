import { writeFile } from 'node:fs/promises';
import { BOARD } from '../src/game/rules/data.js';
import { CARDS } from '../src/game/cards/decks.js';
const q = (v) =>
  v === null || v === undefined
    ? 'null'
    : typeof v === 'number'
      ? String(v)
      : `'${String(v).replaceAll("'", "''")}'`;
const uuid = (i) => `00000000-0000-4000-8000-${String(i).padStart(12, '0')}`;
let sql = '-- Original thematic catalog. Generated by scripts/seed-catalog.js.\n';
for (const t of BOARD.filter((t) => t.price))
  sql += `insert into properties(id,board_index,name,kind,color_group,description,price,rent_schedule,mortgage_value,development_cost,source_url) values(${q(uuid(t.id))},${t.id},${q(t.name)},${q(t.type)},${q(t.group)},${q(t.description)},${t.price},${t.rents ? `array[${t.rents}]` : 'null'},${t.mortgage},${q(t.buildCost)},${q(t.source)});\n`;
sql += `insert into card_decks(id,key,title) values(${q(uuid(100))},'force','Force Events'),(${q(uuid(101))},'galactic','Galactic Events');\n`;
CARDS.forEach(
  (c, i) =>
    (sql += `insert into card_definitions(id,key,deck_id,title,description,effect_type,effect_value,target,retainable) values(${q(uuid(200 + i))},${q(c.id)},${q(uuid(c.deck === 'force' ? 100 : 101))},${q(c.title)},${q(c.description)},${q(c.effect)},${q(c.value)},${q(c.target)},${c.retainable});\n`),
);
sql +=
  "insert into achievements(key,title,description) values('first-victory','Ruler of the Galaxy','Win your first online conquest.'),('first-world','A World of Your Own','Acquire your first planet.');\n";
await writeFile('supabase/migrations/202611190003_catalog.sql', sql);
await writeFile(
  'supabase/seed.sql',
  '-- Catalog is seeded by migration 202611190003; no duplicate seed inserts.\n',
);
console.log('28 purchasable spaces and 24 original cards added to the catalog migration.');
